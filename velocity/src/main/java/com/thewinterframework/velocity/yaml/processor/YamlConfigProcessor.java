package com.thewinterframework.velocity.yaml.processor;

import com.google.auto.service.AutoService;
import com.thewinterframework.processor.context.ProcessorContext;
import com.thewinterframework.processor.handler.WinterAnnotationProcessor;
import com.thewinterframework.processor.template.TemplateBuilder;
import com.thewinterframework.velocity.yaml.FileName;
import com.thewinterframework.velocity.yaml.YamlConfig;

import javax.lang.model.element.Element;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.TypeElement;
import java.lang.annotation.Annotation;
import java.util.Set;
import java.util.TreeSet;

@AutoService(WinterAnnotationProcessor.class)
public class YamlConfigProcessor implements WinterAnnotationProcessor {

	private final Set<String> fileNames = new TreeSet<>();

	@Override
	public Set<Class<? extends Annotation>> getSupportedAnnotations() {
		return Set.of(FileName.class);
	}

	@Override
	public void handle(final TypeElement annotation, final Set<? extends Element> elements, final ProcessorContext ctx) {
		for (final var element : elements) {
			final var type = element instanceof ExecutableElement method ? method.getReturnType() : element.asType();
			if (!type.toString().equals(YamlConfig.class.getCanonicalName())) {
				ctx.messager().printError("@FileName must qualify a Velocity YamlConfig", element);
				continue;
			}
			fileNames.add(element.getAnnotation(FileName.class).value());
		}
	}

	@Override
	public void onRoundEnd(final ProcessorContext ctx) {
		if (!fileNames.isEmpty()) {
			ctx.wireModule(ctx.getWinterModuleQualifiedNameStringFor("VelocityYamlConfigModule"));
		}
	}

	@Override
	public void onProcessingComplete(final ProcessorContext ctx) {
		if (fileNames.isEmpty()) {
			return;
		}
		TemplateBuilder.fromResource("generated/velocity/AutoGeneratedYamlConfigModule.java")
				.placeholder("PACKAGE_NAME", ctx.getWinterModulePackageString())
				.placeholder("FILE_NAMES", String.join(", ", fileNames.stream().map(YamlConfigProcessor::literal).toList()))
				.write(ctx, ctx.getWinterModuleQualifiedNameStringFor("VelocityYamlConfigModule"));
	}

	private static String literal(final String value) {
		return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"")
				.replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t") + "\"";
	}
}
